/**
 * Generate src/app/ctlMethods.ts from wire*Ctl assignments in *Ctl.ts files.
 * Run: node scripts/gen-ctl-methods.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const appDir = path.resolve(import.meta.dirname, '../src/app');
const ctlFiles = [
  'activityCtl.ts',
  'hallwayCtl.ts',
  'messagesCtl.ts',
  'profileCtl.ts',
  'roomCtl.ts',
  'settingsCtl.ts',
  'studioCtl.ts',
];

const imports = [];
const fields = [];

for (const file of ctlFiles) {
  const src = fs.readFileSync(path.join(appDir, file), 'utf8');
  const mod = file.replace(/\.ts$/, '');
  const alias = mod.replace(/Ctl$/, 'Ctl');
  const methods = [...src.matchAll(/proto\.(\w+)\s*=\s*(\w+)/g)].map((m) => ({
    prop: m[1],
    fn: m[2],
  }));
  if (!methods.length) continue;
  imports.push(`import type * as ${alias} from './${mod}.ts';`);
  for (const { prop, fn } of methods) {
    fields.push(`  ${prop}: typeof ${alias}.${fn};`);
  }
}

const out = `/* Generated by scripts/gen-ctl-methods.mjs — do not edit by hand. */
${imports.join('\n')}

/** Methods attached to ClubboxApp.prototype by wire*Ctl. */
export type ClubboxAppCtlMethods = {
${fields.join('\n')}
};
`;

fs.writeFileSync(path.join(appDir, 'ctlMethods.ts'), out);
console.log(`Wrote ctlMethods.ts (${fields.length} methods)`);
