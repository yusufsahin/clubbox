/**
 * Build Clubbox-*-setup.exe from an existing win-unpacked folder using makensis
 * directly — no electron-builder uninstaller stub (blocked by Smart App Control).
 *
 * Prerequisites: npm run dist:dir (or a prior dist that left win-unpacked).
 */
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const version = pkg.version
const productName = pkg.productName || 'Clubbox'
const releaseDir = path.resolve(root, pkg.build?.directories?.output || '../clubdeck-app/release')
const unpacked = path.join(releaseDir, 'win-unpacked')
const outExe = path.join(releaseDir, `${productName}-${version}-setup.exe`)
const icon = path.join(root, 'build', 'icon.ico')

function findMakensis() {
  const cache = path.join(os.homedir(), 'AppData', 'Local', 'electron-builder', 'Cache')
  if (!fs.existsSync(cache)) return null
  const stack = [cache]
  while (stack.length) {
    const dir = stack.pop()
    for (const name of fs.readdirSync(dir)) {
      const full = path.join(dir, name)
      let st
      try {
        st = fs.statSync(full)
      } catch {
        continue
      }
      if (st.isDirectory()) stack.push(full)
      else if (name.toLowerCase() === 'makensis.exe') return full
    }
  }
  return null
}

if (!fs.existsSync(path.join(unpacked, `${productName}.exe`))) {
  console.error(`make-win-setup: missing ${unpacked}\\${productName}.exe — run npm run dist:dir first`)
  process.exit(1)
}

const makensis = findMakensis()
if (!makensis) {
  console.error('make-win-setup: makensis.exe not found under %LOCALAPPDATA%\\electron-builder\\Cache')
  process.exit(1)
}

const nsiPath = path.join(releaseDir, `_clubbox-setup-${version}.nsi`)
const unpackedPosix = unpacked.replace(/\\/g, '/')
const outPosix = outExe.replace(/\\/g, '/')
const iconPosix = icon.replace(/\\/g, '/')
const iconLine = fs.existsSync(icon) ? `!define MUI_ICON "${iconPosix}"\n!define MUI_UNICON "${iconPosix}"\n` : ''

const nsi = `; Auto-generated by scripts/make-win-setup.mjs — do not edit.
Unicode true
Name "${productName}"
OutFile "${outPosix}"
InstallDir "$LOCALAPPDATA\\Programs\\${productName}"
InstallDirRegKey HKCU "Software\\${productName}" "InstallLocation"
RequestExecutionLevel user
SetCompressor /SOLID lzma

!include "MUI2.nsh"
${iconLine}!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Section "Install"
  SetOutPath "$INSTDIR"
  File /r "${unpackedPosix}\\*.*"
  WriteUninstaller "$INSTDIR\\Uninstall.exe"
  CreateDirectory "$SMPROGRAMS\\${productName}"
  CreateShortCut "$SMPROGRAMS\\${productName}\\${productName}.lnk" "$INSTDIR\\${productName}.exe"
  CreateShortCut "$DESKTOP\\${productName}.lnk" "$INSTDIR\\${productName}.exe"
  WriteRegStr HKCU "Software\\${productName}" "InstallLocation" "$INSTDIR"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}" "DisplayName" "${productName} ${version}"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}" "UninstallString" '"$INSTDIR\\Uninstall.exe"'
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}" "DisplayIcon" "$INSTDIR\\${productName}.exe"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}" "Publisher" "Clubbox"
  WriteRegStr HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}" "DisplayVersion" "${version}"
SectionEnd

Section "Uninstall"
  Delete "$DESKTOP\\${productName}.lnk"
  Delete "$SMPROGRAMS\\${productName}\\${productName}.lnk"
  RMDir "$SMPROGRAMS\\${productName}"
  RMDir /r "$INSTDIR"
  DeleteRegKey HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\${productName}"
  DeleteRegKey HKCU "Software\\${productName}"
SectionEnd
`

fs.mkdirSync(releaseDir, { recursive: true })
fs.writeFileSync(nsiPath, nsi, 'utf8')
console.log(`make-win-setup: makensis → ${outExe}`)

const result = spawnSync(makensis, ['/V2', nsiPath], {
  cwd: releaseDir,
  stdio: 'inherit',
  windowsHide: true,
})

try {
  fs.unlinkSync(nsiPath)
} catch {
  /* ignore */
}

if (result.status !== 0) {
  console.error(`make-win-setup: makensis failed (exit ${result.status})`)
  process.exit(result.status ?? 1)
}

const st = fs.statSync(outExe)
console.log(`make-win-setup: ok ${outExe} (${st.size} bytes)`)
