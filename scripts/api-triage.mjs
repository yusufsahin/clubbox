import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
  appendFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const require = createRequire(import.meta.url);
const { outputHasLeak } = require('../electron/redact.cjs');

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function defaultLogDir() {
  if (process.env.CLUBBOX_API_LOG) return process.env.CLUBBOX_API_LOG;
  const home = process.env.APPDATA || process.env.HOME || ROOT;
  if (process.env.APPDATA) return join(process.env.APPDATA, 'Clubbox', 'api-log');
  return join(home, '.config', 'Clubbox', 'api-log');
}

export function readJsonlDir(dir) {
  if (!existsSync(dir)) return [];
  const records = [];
  for (const name of readdirSync(dir).filter((n) => n.endsWith('.jsonl')).sort()) {
    const text = readFileSync(join(dir, name), 'utf8');
    for (const line of text.split(/\r?\n/)) {
      if (!line.trim()) continue;
      if (outputHasLeak(line)) continue;
      try {
        records.push(JSON.parse(line));
      } catch {
        // skip bad lines
      }
    }
  }
  return records;
}

export function failureKey(record) {
  const error = String(record.error || record.message || '').slice(0, 120);
  return `${record.endpoint}|${record.status}|${error}`;
}

export function groupFailures(records) {
  const groups = new Map();
  for (const record of records) {
    const status = Number(record.status) || 0;
    // Agora success (status 200) and connection-state chatter are not product failures.
    if (record.kind === 'agora') {
      if (record.ok === true || status >= 200) continue;
      if (record.endpoint === 'agora_connection') continue;
      // Keep agora_join (and similar) hard failures: status 0 / ok false.
    } else if (status < 400 && record.kind !== 'pubnub-unknown') {
      continue;
    }
    if (record.kind === 'web_api' && status < 400) continue;
    const key = failureKey(record);
    if (!groups.has(key)) groups.set(key, record);
  }
  return groups;
}

function slug(endpoint, status) {
  return `${String(endpoint).replace(/[^\w-]+/g, '_')}-${status}`;
}

export function triage(options = {}) {
  const root = options.root ?? ROOT;
  const logDir = options.logDir ?? defaultLogDir();
  const liveDir = options.liveDir ?? join(root, 'tests/live-failures');
  const routesPath = options.routesPath ?? join(root, 'electron/webApiRoutes.json');
  const realtimePath = options.realtimePath ?? join(root, 'docs/api/realtime.md');
  const reportPath = options.reportPath ?? join(root, 'reports/triage.md');
  const runDocs = options.runDocs !== false;

  mkdirSync(liveDir, { recursive: true });
  mkdirSync(dirname(reportPath), { recursive: true });

  const records = readJsonlDir(logDir);
  const pendingPath = join(logDir, 'triage-pending.json');
  if (existsSync(pendingPath)) {
    try {
      const pending = JSON.parse(readFileSync(pendingPath, 'utf8'));
      if (Array.isArray(pending?.failures)) {
        for (const row of pending.failures) {
          if (row && typeof row.endpoint === 'string') records.push(row);
        }
      }
    } catch {
      // ignore corrupt pending file
    }
  }
  const failures = groupFailures(records);
  const created = [];
  const promoted = [];
  const pubnubNotes = [];

  for (const [, record] of failures) {
    if (record.kind === 'pubnub-unknown') {
      const line = `- \`${record.endpoint || record.type || 'unknown'}\` keys: ${(record.bodyKeys || []).join(', ')}`;
      const current = existsSync(realtimePath) ? readFileSync(realtimePath, 'utf8') : '';
      if (!current.includes('## Seen live, not handled')) {
        appendFileSync(realtimePath, `\n## Seen live, not handled\n\n${line}\n`, 'utf8');
        pubnubNotes.push(line);
      } else if (!current.includes(line)) {
        appendFileSync(realtimePath, `${line}\n`, 'utf8');
        pubnubNotes.push(line);
      }
      continue;
    }

    const name = slug(record.endpoint, record.status);
    const testPath = join(liveDir, `${name}.test.ts`);
    const fixturePath = join(liveDir, `${name}.json`);
    if (existsSync(testPath)) continue;

    const fixture = {
      endpoint: record.endpoint,
      status: record.status,
      bodyKeys: record.bodyKeys || [],
      error: record.error || '',
      evidence: record.evidence || '',
    };
    const fixtureLine = `${JSON.stringify(fixture, null, 2)}\n`;
    if (outputHasLeak(fixtureLine)) continue;
    writeFileSync(fixturePath, fixtureLine, 'utf8');

    const testSource = `import assert from 'node:assert/strict';
import test from 'node:test';
import fixture from './${name}.json' with { type: 'json' };
import { ClubhouseApiClient } from '../../src/api/client.ts';
import { FakeTransport } from '../../features/support/fakeTransport.ts';

/** Generated by api:triage from a live failure. Fix the product behaviour, then keep this green. */
test('live failure ${record.endpoint} ${record.status}', async () => {
  const transport = new FakeTransport();
  transport.willAnswer(fixture.endpoint, fixture.status, 1);
  const client = new ClubhouseApiClient({
    useSandbox: false,
    webSession: true,
    experimentalActions: true,
    transport,
  });
  try {
    const body = Object.fromEntries((fixture.bodyKeys || []).map((key) => [key, key === 'channel' ? 'abc123' : 1]));
    await client.callEndpoint(fixture.endpoint, body);
    assert.fail('expected the live failure status');
  } catch (err) {
    assert.ok(err);
  }
  assert.ok(client.getApiHealth().some((entry) => entry.endpoint === fixture.endpoint && entry.status === fixture.status));
});
`;
    if (outputHasLeak(testSource)) continue;
    writeFileSync(testPath, testSource, 'utf8');
    created.push(name);
  }

  // Promote 2xx bundle/community routes
  const routes = JSON.parse(readFileSync(routesPath, 'utf8'));
  let routesChanged = false;
  for (const record of records) {
    const status = Number(record.status) || 0;
    if (status < 200 || status >= 300) continue;
    const route = routes[record.endpoint];
    if (!route) continue;
    if (route.evidence !== 'bundle' && route.evidence !== 'community') continue;
    route.evidence = 'observed';
    routesChanged = true;
    promoted.push(record.endpoint);
  }
  if (routesChanged) {
    writeFileSync(routesPath, `${JSON.stringify(routes, null, 2)}\n`, 'utf8');
    if (runDocs) {
      spawnSync(process.execPath, [join(root, 'scripts/api-docs.mjs')], { cwd: root, stdio: 'ignore' });
    }
  }

  const uniquePromoted = [...new Set(promoted)];
  const summary = [
    '# API triage',
    '',
    `Log dir: ${logDir}`,
    `New failure tests: ${created.length}`,
    `Promoted routes: ${uniquePromoted.length}`,
    `PubNub notes: ${pubnubNotes.length}`,
    '',
    created.length ? created.map((n) => `- tests/live-failures/${n}.test.ts`).join('\n') : '_No new failure tests_',
    '',
    uniquePromoted.length ? uniquePromoted.map((n) => `- ${n} → observed`).join('\n') : '_No promotions_',
    '',
  ].join('\n');
  writeFileSync(reportPath, summary, 'utf8');

  const changed = created.length + uniquePromoted.length + pubnubNotes.length;
  return {
    created,
    promoted: uniquePromoted,
    pubnubNotes,
    changed,
    message: changed === 0 ? 'NO NEW FAILURES' : `created ${created.length}, promoted ${uniquePromoted.length}`,
  };
}

function main() {
  const result = triage();
  console.log(result.message);
  if (result.changed === 0) console.log('NO NEW FAILURES');
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) main();
